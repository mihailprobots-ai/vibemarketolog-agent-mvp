def build_marketing_prompt(payload: dict) -> str:
    return f"""
Проанализируй бизнес и подготовь маркетинговый анализ.

Вводные:
- Название бизнеса: {payload["business_name"]}
- Ниша: {payload["industry"]}
- Описание продукта: {payload["product"]}
- Целевая аудитория: {payload["audience"]}
- География: {payload["location"]}
- Бюджет на рекламу: {payload["budget"]}
- Главная цель: {payload["goal"]}

Нужно:
1. Коротко оценить бизнес, продукт, рынок и точки роста.
2. Разложить целевую аудиторию на понятные сегменты.
3. Предложить 3 рекламные гипотезы для теста.
4. Предложить 5 вариантов оффера.
5. Предложить идеи рекламных креативов для запуска.
6. Дать список следующих действий на 7 дней.

Важно:
- пиши на русском языке;
- избегай общих фраз вроде "улучшить маркетинг";
- гипотезы должны быть проверяемыми;
- офферы должны быть пригодны для рекламы;
- рекомендации должны учитывать бюджет и географию;
- верни строго JSON по заданной системной схеме.
""".strip()
